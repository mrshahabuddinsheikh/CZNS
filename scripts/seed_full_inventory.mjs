function parseColors(colorStr) {
  if (!colorStr) return [{ name: 'Standard', hex: '#333333' }];
  const parts = colorStr.split(/[\/\+]/).map(s => s.trim().toLowerCase());
  const res = [];
  for (const p of parts) {
    if (COLOR_MAP[p]) {
      res.push(COLOR_MAP[p]);
    } else {
      res.push({ name: p.toUpperCase(), hex: '#444444' });
    }
  }
  return res.length > 0 ? res : [{ name: 'Standard', hex: '#333333' }];
}

